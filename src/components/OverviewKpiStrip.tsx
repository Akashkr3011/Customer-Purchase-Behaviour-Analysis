import React from 'react';
import { CustomerSummary, SegmentMetrics, CleaningReport } from '../types/analytics';
import { DollarSign, Users, Repeat, ShoppingBag, Award, CheckCircle2 } from 'lucide-react';

interface OverviewKpiStripProps {
  summaries: CustomerSummary[];
  segmentMetrics: SegmentMetrics[];
  totalTransactions: number;
  repeatRate: number;
  repeatBuyerCount: number;
  report: CleaningReport;
}

export const OverviewKpiStrip: React.FC<OverviewKpiStripProps> = ({
  summaries,
  segmentMetrics,
  totalTransactions,
  repeatRate,
  repeatBuyerCount,
  report,
}) => {
  const totalRevenue = summaries.reduce((acc, c) => acc + c.total_spend, 0);
  const totalOrders = summaries.reduce((acc, c) => acc + c.order_count, 0);
  const overallAov = totalOrders > 0 ? (totalRevenue / totalOrders).toFixed(2) : '0.00';

  const highSpendSeg = segmentMetrics.find((s) => s.segment === 'High Spend');
  const highSpendRevShare = highSpendSeg ? highSpendSeg.revenue_share : 0;
  const highSpendCustShare = highSpendSeg ? highSpendSeg.customer_share : 0;

  return (
    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-5 gap-4">
      {/* KPI 1: Gross Sales */}
      <div className="bg-white border border-slate-200 rounded p-4">
        <div className="flex items-center justify-between text-xs font-medium text-slate-500 mb-1">
          <span>Total Gross Spend</span>
          <DollarSign className="w-4 h-4 text-slate-400" />
        </div>
        <div className="text-2xl font-bold font-mono tabular-nums text-slate-900 tracking-tight">
          ₹{totalRevenue.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
        </div>
        <div className="text-xs text-slate-500 mt-1 font-mono">
          Across {totalTransactions.toLocaleString('en-IN')} line items
        </div>
      </div>

      {/* KPI 2: Total Customers */}
      <div className="bg-white border border-slate-200 rounded p-4">
        <div className="flex items-center justify-between text-xs font-medium text-slate-500 mb-1">
          <span>Active Customers</span>
          <Users className="w-4 h-4 text-slate-400" />
        </div>
        <div className="text-2xl font-bold font-mono tabular-nums text-slate-900 tracking-tight">
          {summaries.length.toLocaleString('en-IN')}
        </div>
        <div className="text-xs text-slate-500 mt-1">
          {totalOrders.toLocaleString('en-IN')} total shopping orders
        </div>
      </div>

      {/* KPI 3: Repeat Customer Rate */}
      <div className="bg-white border border-slate-200 rounded p-4">
        <div className="flex items-center justify-between text-xs font-medium text-slate-500 mb-1">
          <span>Repeat Purchase Rate</span>
          <Repeat className="w-4 h-4 text-slate-400" />
        </div>
        <div className="text-2xl font-bold font-mono tabular-nums text-emerald-700 tracking-tight">
          {repeatRate.toFixed(1)}%
        </div>
        <div className="text-xs text-slate-500 mt-1">
          {repeatBuyerCount} repeat buyers (2+ orders)
        </div>
      </div>

      {/* KPI 4: Average Order Value */}
      <div className="bg-white border border-slate-200 rounded p-4">
        <div className="flex items-center justify-between text-xs font-medium text-slate-500 mb-1">
          <span>Average Order Value</span>
          <ShoppingBag className="w-4 h-4 text-slate-400" />
        </div>
        <div className="text-2xl font-bold font-mono tabular-nums text-slate-900 tracking-tight">
          ₹{Number(overallAov).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}
        </div>
        <div className="text-xs text-slate-500 mt-1 font-mono">
          ₹{(totalRevenue / (summaries.length || 1)).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} spend / customer
        </div>
      </div>

      {/* KPI 5: VIP Revenue Concentration */}
      <div className="bg-white border border-slate-200 rounded p-4">
        <div className="flex items-center justify-between text-xs font-medium text-slate-500 mb-1">
          <span>High-Spend Pareto</span>
          <Award className="w-4 h-4 text-slate-400" />
        </div>
        <div className="text-2xl font-bold font-mono tabular-nums text-indigo-700 tracking-tight">
          {highSpendRevShare}%
        </div>
        <div className="text-xs text-slate-500 mt-1">
          Generated by top {highSpendCustShare}% customers
        </div>
      </div>
    </div>
  );
};
